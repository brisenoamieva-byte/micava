export function isMexicoCountry(country: string | null | undefined): boolean {
  const c = (country ?? "")
    .trim()
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
  return c === "mexico";
}
